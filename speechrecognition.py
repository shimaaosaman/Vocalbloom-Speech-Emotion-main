def build_enhanced_cnn_lstm_attention(shape, classes, filters=64):
    inp = Input(shape=shape)
    x = Conv2D(filters, kernel_size=(shape[0], 1), padding='valid', activation='relu')(inp)
    x = Reshape((shape[1], filters))(x)
    x = Conv1D(128, kernel_size=3, padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = MaxPooling1D(pool_size=2)(x)
    x = Dropout(0.3)(x)
    x = Conv1D(128, kernel_size=3, padding='same', activation='relu')(x)
    x = BatchNormalization()(x)
    x = MaxPooling1D(pool_size=2)(x)
    x = Dropout(0.3)(x)
    x = Bidirectional(LSTM(128, return_sequences=True))(x) # return_sequences=True for attention
    x = AttentionLayer()(x) # Apply attention
    x = Dropout(0.5)(x)
    x = Dense(128, activation="relu")(x)
    x = Dropout(0.5)(x)
    out = Dense(classes, activation="softmax")(x)
    model = Model(inp, out)
    return model

