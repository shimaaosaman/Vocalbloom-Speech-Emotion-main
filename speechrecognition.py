def prepare_single(path):
    feat = extract_features(path)

    if feat.shape[1] < MAX_LEN:
        pad = MAX_LEN - feat.shape[1]
        feat = np.pad(feat, ((0, 0), (0, pad)), mode='constant')
    else:
        feat = feat[:, :MAX_LEN]

    feat = feat.reshape(1, feat.shape[0], feat.shape[1], 1)
    feat_flat = feat.reshape(1, -1)
    feat_scaled = scaler.transform(feat_flat)
    feat_final = feat_scaled.reshape(feat.shape)

    return feat_final


def predict_all(path):
    if path is None:
        return {"error": "Please upload an audio file!"}

    try:
        Xp = prepare_single(path)

        emo = final_model.predict(Xp, verbose=0)[0]
        gen = gender_model.predict(Xp, verbose=0)[0]
        spk = speaker_model.predict(Xp, verbose=0)[0]

        return {
            "emotion": emotions_list[np.argmax(emo)],
            "gender": gender_list[np.argmax(gen)],
            "speaker": f"Actor_{speaker_list[np.argmax(spk)]}",
        }

    except Exception as e:
        return {"error": f"Error processing audio: {str(e)}"}


def infer(audio):
    if audio is None:
        return {"error": "Please upload an audio file!"}
    return predict_all(audio)


